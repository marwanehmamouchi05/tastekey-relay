import type {
  Profile,
  Preference,
  Category,
  Entity,
  Evidence,
} from "../shared-types";
export const emptyProfile = (): Profile => ({
  version: 1,
  nodes: [],
  consents: {},
  budgets: {},
  history: [],
});
const stamp = () => new Date().toISOString();
const evidence = (
  detail: string,
  source: Evidence["source"] = "user",
): Evidence => ({ id: crypto.randomUUID(), source, detail, at: stamp() });
export function addPreference(
  p: Profile,
  label: string,
  category: Category,
  entity?: Entity,
): Profile {
  if (!label.trim()) return p;
  const id = crypto.randomUUID(),
    ev = evidence(`You added ${label}.`);
  const node: Preference = {
    id,
    label: label.trim(),
    category,
    status: "stated",
    entity,
    evidence: [ev],
    updatedAt: stamp(),
  };
  // These are questions to test, never Qloo claims or personal facts.
  const hypotheses: Record<string, string[]> = {
    movie: [
      "Visual world-building",
      "Emotional storytelling",
      "Mystery and discovery",
    ],
    tv_show: ["Character-driven stories", "Unexpected twists"],
    artist: ["The atmosphere", "The lyrics"],
    book: ["The writing style", "The ideas"],
    brand: ["The design", "The function"],
    destination: ["Architecture and design", "Local culture"],
    place: ["The atmosphere", "The experience"],
    design: ["Materials and form", "The atmosphere"],
  };
  const nodes = (hypotheses[category] ?? []).map((label) => ({
    id: crypto.randomUUID(),
    label,
    category,
    status: "inferred" as const,
    parentId: id,
    evidence: [
      evidence(
        `Possible reason for liking ${node.label}; generated by a question template, unverified.`,
        "rule",
      ),
    ],
    updatedAt: stamp(),
  }));
  return {
    ...p,
    nodes: [...p.nodes, node, ...nodes],
    history: [...p.history, ev],
  };
}
export function nextQuestion(p: Profile) {
  const uncertain = p.nodes.filter(
    (n) =>
      n.status === "inferred" &&
      n.parentId &&
      p.nodes.some(
        (parent) =>
          parent.id === n.parentId &&
          ["stated", "confirmed"].includes(parent.status),
      ) &&
      !p.nodes.some(
        (answer) =>
          answer.parentId === n.parentId && answer.status === "confirmed",
      ),
  );
  const groups = new Map<string, Preference[]>();
  for (const n of uncertain)
    groups.set(n.parentId!, [...(groups.get(n.parentId!) ?? []), n]);
  // Prefer the unresolved parent affecting the greatest number of currently authorized contexts.
  const ranked = [...groups.entries()].sort((a, b) => {
    const impact = (id: string, count: number) =>
      count +
      Object.values(p.consents).filter(
        (c) =>
          c && Date.parse(c.expiresAt) > Date.now() && c.nodeIds.includes(id),
      ).length *
        2;
    return impact(b[0], b[1].length) - impact(a[0], a[1].length);
  });
  if (!ranked.length) return null;
  const [parentId, options] = ranked[0];
  return {
    parent: p.nodes.find((n) => n.id === parentId)!,
    options,
    reason:
      "Prioritized by unresolved interpretations and the number of authorized experiences affected.",
  };
}
export function verify(
  p: Profile,
  parentId: string,
  selected: string | null,
): Profile {
  if (
    selected !== null &&
    !p.nodes.some(
      (n) =>
        n.id === selected && n.parentId === parentId && n.status === "inferred",
    )
  )
    return p;
  const ev = evidence(
    selected
      ? `Confirmed interpretation: ${p.nodes.find((n) => n.id === selected)?.label}. Other interpretations remain uncertain.`
      : "None of the proposed interpretations fit.",
  );
  return {
    ...p,
    nodes: p.nodes.map((n) =>
      n.parentId === parentId && n.status === "inferred"
        ? {
            ...n,
            status:
              n.id === selected
                ? "confirmed"
                : selected === null
                  ? "rejected"
                  : "inferred",
            updatedAt: stamp(),
            evidence: [...n.evidence, ev],
          }
        : n,
    ),
    history: [...p.history, ev],
  };
}
export function editPreference(
  p: Profile,
  id: string,
  label: string,
  status: Preference["status"],
): Profile {
  const ev = evidence(`Preference edited to “${label}” (${status}).`);
  return {
    ...p,
    nodes: p.nodes.map((n) =>
      n.id === id
        ? {
            ...n,
            label,
            status,
            updatedAt: stamp(),
            evidence: [...n.evidence, ev],
          }
        : n,
    ),
    history: [...p.history, ev],
  };
}
export function removePreference(p: Profile, id: string): Profile {
  const removed = new Set(
    p.nodes.filter((n) => n.id === id || n.parentId === id).map((n) => n.id),
  );
  return {
    ...p,
    nodes: p.nodes.filter((n) => !removed.has(n.id)),
    consents: Object.fromEntries(
      Object.entries(p.consents).map(([k, v]) => [
        k,
        { ...v, nodeIds: v!.nodeIds.filter((n) => !removed.has(n)) },
      ]),
    ),
  };
}
export function setBudget(
  p: Profile,
  context: "shopping" | "travel",
  amount: number,
): Profile {
  const ev = evidence(
    `Set ${context} budget to ${amount} USD. Aesthetic tastes were preserved.`,
  );
  return {
    ...p,
    budgets: { ...p.budgets, [context]: amount },
    history: [...p.history, ev],
  };
}

/** Omit exact reviewed references and duplicate IDs, without guessing that remakes are identical. */
export function recommendationCandidates(
  entities: Entity[],
  referenceIds: string[],
) {
  const seen = new Set(referenceIds);
  return entities.filter((entity) => {
    if (seen.has(entity.id)) return false;
    seen.add(entity.id);
    return true;
  });
}
const metadataWords = (value: string) =>
  value.toLowerCase().match(/[\p{L}\p{N}]+/gu) ?? [];
const uninformativeWords = new Set([
  "the",
  "and",
  "with",
  "this",
  "that",
  "like",
  "love",
  "for",
  "its",
]);
/** A conservative text hint, not a semantic preference probability. Names are not evidence. */
export function verifiedMetadataSupport(
  entity: Entity,
  preferences: Preference[],
): number {
  const documents = [entity.description || "", ...entity.tags].map(
    metadataWords,
  );
  const answers = preferences
    .filter((n) => n.status === "confirmed" && !n.entity)
    .map((n) => [
      ...new Set(
        metadataWords(n.label).filter(
          (w) => w.length > 3 && !uninformativeWords.has(w),
        ),
      ),
    ])
    .filter((words) => words.length);
  // Require every informative word in the same metadata field. Nearby negation abstains.
  return answers.some((words) =>
    documents.some((tokens) =>
      words.every((word) =>
        tokens.some(
          (token, i) =>
            token === word &&
            !tokens
              .slice(Math.max(0, i - 3), i)
              .some((t) => ["not", "no", "never", "without"].includes(t)),
        ),
      ),
    ),
  )
    ? 1
    : 0;
}
/** Preserve the provider prior: a complete confirmed metadata hint can move an item at most one position. */
export function rankByVerifiedMetadata(
  entities: Entity[],
  preferences: Preference[],
): Entity[] {
  return entities
    .map((entity, index) => ({
      entity,
      index,
      score: index - 1.1 * verifiedMetadataSupport(entity, preferences),
    }))
    .sort((a, b) => a.score - b.score || a.index - b.index)
    .map((e) => e.entity);
}
